const dicts: Record<Lang, Record<StringKey, string>> = { en, vi };

export function translate(lang: Lang, key: StringKey, vals?: Vals): string {
  let out: string = dicts[lang][key] ?? en[key];
  if (vals) {
    for (const [name, value] of Object.entries(vals)) {
      out = out.replaceAll(`{${name}}`, String(value));
    }
  }
  return out;
}

// Server replies carry English messages; map them back to a key and re-render
// in the player's language. Unknown messages pass through untouched.
const serverErrorKeys = new Map<string, StringKey>(
  (Object.keys(en) as StringKey[])
    .filter((key) => key.startsWith('err.'))
    .map((key) => [en[key], key]),
);

export function translateServerError(lang: Lang, message: string): string {
  const key = serverErrorKeys.get(message);
  if (key) return translate(lang, key);
  const match = message.match(/^"(.+)" is a color name — not allowed\.$/);
  if (match) return translate(lang, 'cueError.colorName', { word: match[1] });
  return message;
}
